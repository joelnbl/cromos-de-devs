export const dictionaries: Record<Locale, Dict> = { es, en };

export type ErrorCode = keyof Dict["errors"];

/** Mensajes que lanza la base de datos (en español) → código traducible. */
const DB_ERRORS: Record<string, ErrorCode> = {
  "Necesitas entrar con GitHub": "needLogin",
  "Todavía no tienes cromo": "noCardYet",
  "Ya abriste el sobre de hoy": "alreadyOpened",
  "Elige dos cromos distintos": "sameCard",
  "Solo puedes ofrecer cromos repetidos": "onlyDupes",
  "Ese cromo no existe": "cardMissing",
  "Tienes demasiados cambios abiertos": "tooManyTrades",
  "Ese cambio no existe": "tradeMissing",
  "Ese cambio ya no está disponible": "tradeClosed",
  "No puedes aceptar tu propio cambio": "ownTrade",
  "No tienes ese cromo": "youDontHave",
  "Ya tienes ese cromo": "youAlreadyHave",
};

export function errorCodeOf(message: string | undefined | null): ErrorCode {
  if (!message) return "generic";
  for (const [text, code] of Object.entries(DB_ERRORS)) if (message.includes(text)) return code;
  return "generic";
}

/** Texto de un error que llega por la URL (?error=código). Acepta textos antiguos. */
export function errorText(t: Dict, value: string | undefined): string | null {
  if (!value) return null;
  return value in t.errors ? t.errors[value as ErrorCode] : value;
}

export function pickLocale(acceptLanguage: string | null | undefined): Locale {
  const first = (acceptLanguage ?? "").split(",")[0]?.trim().toLowerCase() ?? "";
  if (!first) return "es";
  return first.startsWith("es") ? "es" : "en";
}
